// Actor strings are formatted as `<kind>:<name>` (e.g. `human:jonathan`,
// `shell:shell-A`, `agent:tachikoma`, `integration:github`,
// `major:auto-triage`, `major:reaper`). Stored as plain text — typed open here
// so callers can compose without constant re-narrowing.
export type ActorKind = 'human' | 'agent' | 'shell' | 'integration' | 'major';
export type ActorString = `${ActorKind}:${string}`;

// Common Event types observed in SPEC. Open via `(string & {})` so
// integrations adding new event names don't require a types.ts change.
export type KnownEventType =
  | 'brief-created'
  | 'status-transitioned'
  | 'run-started'
  | 'run-ended'
  | 'accepted'
  | 'rejected'
  | 'human-handoff'
  | 'relationship-added'
  | 'content-revision-added'
  | 'artifact-produced'
  | 'queue-rank-set';
export type EventType = KnownEventType | (string & Record<never, never>);

// Common Telemetry observation types observed in SPEC. Open in the same way.
export type KnownTelemetryObservation =
  | 'failed-claim-attempt'
  | 'heartbeat-lapse'
  | 'external-system-error'
  | 'retry-attempt'
  | 'repair-inspection-trigger';
export type TelemetryObservationType =
  | KnownTelemetryObservation
  | (string & Record<never, never>);

