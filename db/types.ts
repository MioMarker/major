// `events.payload` — discriminated by `events.type`. Only the types where
// SPEC pins a shape are enumerated; the catch-all branch keeps the door open.
export type EventPayload =
  | { kind: 'status-transitioned'; from: BriefStatus; to: BriefStatus; reason?: string }
  | { kind: 'run-started'; runId: number; purpose: RunPurpose; revisionId?: number }
  | {
      kind: 'run-ended';
      runId: number;
      outcome: Exclude<RunOutcome, 'running'>;
      cancellationReason?: RunCancellationReason;
    }
  | { kind: 'human-handoff'; reason: string; expectedAction?: string }
  | {
      kind: 'artifact-produced';
      artifactId: number;
      artifactType: ArtifactType;
      externalRef?: string;
    }
  | { kind: 'relationship-added'; relationshipId: number; type: RelationshipType }
  | { kind: 'content-revision-added'; revisionId: number; revisionNumber: number }
  | { kind: 'queue-rank-set'; queueRank: number; previous?: number }
  | { kind: 'accepted'; prUrl?: string }
  | { kind: 'rejected'; reason?: string }
  | { kind: 'brief-created'; sourceSessionId?: number }
  | Record<string, unknown>;

