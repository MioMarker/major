// Major v1 — TypeScript types for the `major.*` schema.
//
// One exported type per table, named in PascalCase singular.
// snake_case columns map to camelCase fields.
// String-literal unions mirror SQL CHECK constraints; export them so callers
// (functions, shell, ui) can use them in switches without re-deriving.
//
// Conventions:
// - `bigserial` / `bigint` columns → `number`. Supabase-js returns these as
//   numbers when they fit in a JS-safe integer; the orchestrator runs at low
//   volumes so this is fine for v1. Bump to `string` if we ever exceed 2^53.
// - `timestamptz` columns → `Date | string`. Postgres returns ISO strings over
//   the wire; some SDKs parse to Date. Allow both.
// - `jsonb` columns default to `Record<string, unknown>` unless SPEC pins a
//   shape. Where it does (events.payload, telemetry.payload, etc.), a
//   discriminated union or sub-type is provided and re-exported.
// - This file is generated by hand from `0001_initial_schema.sql`. When the
//   schema changes, update both. There is no codegen step in v1.
//
// In-code identifiers and Postgres tables both use the GITS vocabulary
// (Brief / Shell / briefId / shellId in code; briefs / shells / brief_id /
// shell_id in `major.*`) per ADR 004.

